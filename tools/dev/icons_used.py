"""Writes src/app/IconsUsed.h: the Lucide icons src/ uses (ICON_LC_*), the only ones the fonts load.

Lucide has about 1,900 icons and the UI font merges them into each of its sizes; loading all of them filled most of
the font atlas (4096x16384 RGBA at 300 %, 256 MB). The UI uses under 200.

    tools/dev/icons_used.py           rewrite src/app/IconsUsed.h
    tools/dev/icons_used.py --check   exit 1 if it is out of date (ctest icons_used): run it after using a new icon
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "third_party/lucide/IconsLucide.h"
OUT = ROOT / "src/app/IconsUsed.h"
DEFINE = re.compile(r'#define (ICON_LC_[A-Z0-9_]+) "((?:\\x[0-9a-f]{2})+)"')
USE = re.compile(r"\bICON_LC_[A-Z0-9_]+\b")


def codepoints():
    table = {}
    for name, esc in DEFINE.findall(HEADER.read_text(encoding="utf-8")):
        table[name] = ord(bytes(int(h, 16) for h in esc.split("\\x")[1:]).decode("utf-8"))
    return table


def generate():
    table = codepoints()
    used = set()
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix in (".cpp", ".h", ".mm") and path != OUT:
            used.update(n for n in USE.findall(path.read_text(encoding="utf-8", errors="replace")) if n in table)
    cps = sorted({table[n] for n in used})
    ranges, start = [], None
    for i, c in enumerate(cps):  # runs of consecutive codepoints become one range
        if start is None:
            start = c
        if i + 1 == len(cps) or cps[i + 1] != c + 1:
            ranges.append((start, c))
            start = None
    rows, line = [], "    "
    for a, b in ranges:
        item = f"0x{a:04x}, 0x{b:04x}, "
        if len(line) + len(item) > 118:
            rows.append(line.rstrip())
            line = "    "
        line += item
    rows.append(line + "0")
    body = "\n".join(rows)
    return f"""// SculptForge - open source digital sculpting
// SPDX-License-Identifier: GPL-3.0-or-later
//
// Generated by tools/dev/icons_used.py - do not edit. The {len(cps)} Lucide icons src/ uses, the only ones the fonts
// load (all ~1,900 filled most of the font atlas). Using a new ICON_LC_*: run the script (ctest icons_used checks).
#pragma once

#include <imgui.h>

namespace sf {{
inline const ImWchar kUsedIconRanges[] = {{
{body}}};
}} // namespace sf
"""


def main():
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/dev/icons_used.py")
            return 1
        print("icons_used: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
